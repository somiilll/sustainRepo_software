// Generates somewhat randomized data based on industry type to simulate extraction
export const generateMockExtraction = (industry, fileName) => {
  const baseMultiplier = industry === 'Cement' || industry === 'Steel' || industry === 'Aluminium' ? 2 :
    industry === 'Technology' || industry === 'Finance' ? 0.2 : 1;

  const randomValue = (base, variance) => {
    return Math.max(0, Math.round((base + (Math.random() * variance * 2 - variance)) * 100) / 100);
  };

  const randomPage = () => Math.floor(Math.random() * 50) + 5;

  const mockMetric = (val, unit) => ({
    rawTextFound: String(val),
    reasoning: 'Generated by fallback mock logic',
    extractedValue: val,
    reportedUnit: unit,
    normalizedValue: val,
    normalizedUnit: unit,
    page: randomPage()
  });

  return {
    scope1: mockMetric(randomValue(10000 * baseMultiplier, 5000 * baseMultiplier), 'tCO2e'),
    scope2: mockMetric(randomValue(4000 * baseMultiplier, 2000 * baseMultiplier), 'tCO2e'),
    emissionIntensityPerTurnover: mockMetric(randomValue(0.1, 0.05), 'tCO2e/INR'),
    treatedWaterDischarged: mockMetric(randomValue(85, 15), '%'),
    renewableEnergy: mockMetric(randomValue(40, 20), '%'),
    wasteRecycled: mockMetric(randomValue(60, 25), '%'),
    hazardousWaste: mockMetric(randomValue(150 * baseMultiplier, 50 * baseMultiplier), 'tons'),
    wasteIntensity: mockMetric(randomValue(3 * baseMultiplier, 1.5 * baseMultiplier), 'tons/INR'),
    ltirEmployee: mockMetric(randomValue(1.5, 1), 'rate'),
    ltirWorker: mockMetric(randomValue(2.5, 1.5), 'rate'),
    dataPrivacyPolicy: mockMetric(Math.random() > 0.1, null),
    disciplinaryAction: mockMetric(Math.floor(randomValue(1, 2)), 'count'),
    daysAccountsPayable: mockMetric(Math.floor(randomValue(45, 15)), 'days')
  };
};
