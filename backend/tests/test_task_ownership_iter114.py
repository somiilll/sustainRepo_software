MONGO_URL = (os.environ.get("MONGO_URL", "mongodb://localhost:27017")).strip('"')
DB_NAME = (os.environ.get("DB_NAME", "test_database")).strip('"')

ADMIN_EMAIL = "goyalsomil2001@gmail.com"
ADMIN_PASSWORD = "TestUser123!"


# ---------------- Fixtures ----------------
