"""
Iteration 114 - Task Ownership Fields audit trail.

Verifies on `esg_reporting_tasks`:
  1. New tasks generated by task_engine have submitted_by_user_id,
     submitted_at, completed_by_user_id, completed_at, approved_by_user_id,
     approved_at ALL initialized to None.
  2. Submitting a record without approval required sets completed_by_user_id
     and completed_at to the submitting user (plus submitted_by/at).
  3. Submitting a record WITH approval required sets submitted_by/at but
     leaves completed_by_user_id=None (and approved_by_user_id=None).
  4. Approving an approval request sets completed_by_user_id, completed_at,
     approved_by_user_id, approved_at to the approver.
  5. Ownership fields persist after a reassignment (task_assignees change
     does not clear submitted_by / completed_by).
"""
