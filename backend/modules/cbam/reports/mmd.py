"""Monitoring methodology document (MMD) template, pre-filled from installation data.

Section structure follows the monitoring-methodology documentation that operators keep under the CBAM methodology
rules (Impl. Reg. (EU) 2025/2547). It is a working draft for the operator and verifier, not an official form.
"""
import io

from docx import Document
from docx.shared import Pt, RGBColor

GREEN = RGBColor(0x14, 0x53, 0x2D)
TODO = "[To be completed by the operator]"


def _h(doc, text: str, level: int = 1):
    h = doc.add_heading(text, level=level)
    for r in h.runs:
        r.font.color.rgb = GREEN


def _table(doc, headers: list[str], rows: list[list]):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for c, h in zip(t.rows[0].cells, headers):
        c.text = h
    for r in rows:
        cells = t.add_row().cells
        for c, v in zip(cells, r):
            c.text = "" if v is None else (f"{v:,.4g}" if isinstance(v, float) else str(v))
    if not rows:
        t.add_row().cells[0].text = TODO
    doc.add_paragraph()


def build(inst: dict, res: dict, verification: dict) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Arial"
    doc.styles["Normal"].font.size = Pt(10)
    title = doc.add_heading(f"Monitoring methodology document – {inst['name']}", 0)
    for r in title.runs:
        r.font.color.rgb = GREEN
    doc.add_paragraph(f"Reporting period: {res['reporting_year']} · Country: {inst.get('country') or TODO} · "
                      f"Generated by SustainRepo CBAM add-on (draft for operator and verifier review).")

    _h(doc, "1. Installation and operator")
    _table(doc, ["Item", "Value"], [["Installation name", inst["name"]], ["Country", inst.get("country") or TODO],
                                    ["SustainRepo facility", inst.get("facility_id") or TODO], ["Address / UN/LOCODE", TODO],
                                    ["Operator contact", TODO], ["Reporting period", res["reporting_year"]]])

    _h(doc, "2. Installation boundaries and production processes")
    doc.add_paragraph("Describe the system boundaries of each production process, including excluded downstream steps "
                      "(e.g. for steel: plating, cutting, welding, finishing outside the boundary; rolling, reheating, coating "
                      "and galvanising stay inside).")
    _table(doc, ["Process", "CN code", "Sector", "Route", "Activity level (t)", "Indirect in scope"],
           [[p.get("name"), p.get("cn_code"), p.get("sector"), next((x.get("route") for x in inst.get("processes", [])
                                                                       if x["id"] == p["process_id"]), ""),
             p.get("activity_level_t"), "Yes" if p.get("indirect_in_scope") else "No (Annex II)"] for p in res["processes"]])

    _h(doc, "3. Source streams and emission sources")
    doc.add_paragraph("Monitoring approach per source stream (calculation-based: activity data x NCV x EF x OF), the data "
                      "source for each parameter and the tier / default value used.")
    _table(doc, ["Source stream", "Process", "Type", "Unit", "NCV (TJ/unit)", "EF (tCO2/TJ)", "OF", "Data source"],
           [[s.get("name"), s.get("process_id"), s.get("kind"), s.get("unit"), s.get("ncv"), s.get("ef"), s.get("of"),
             "SustainRepo GHG logs" if s.get("source") == "sustainrepo-ghg" else (s.get("source") or TODO)]
            for s in inst.get("source_streams", [])])

    _h(doc, "4. Measurable heat and waste gases")
    _table(doc, ["Process", "Heat imported (TJ)", "EF heat import", "Heat exported (TJ)", "Waste gas imported (TJ)", "Waste gas exported (TJ)"],
           [[p.get("name"), p.get("heat_imp_tj"), p.get("ef_heat_imp"), p.get("heat_exp_tj"), p.get("wg_imp_tj"), p.get("wg_exp_tj")]
            for p in inst.get("processes", [])])

    _h(doc, "5. Electricity")
    _table(doc, ["Process", "Method", "Electricity (MWh)", "EF (tCO2e/MWh)", "EF source"],
           [[p.get("name"), "Process sub-metering" if p.get("el_method", "submetering") == "submetering"
             else f"Allocation ({p.get('el_alloc_basis') or 'production share'}: {p.get('el_alloc_share')})",
             p.get("el_mwh"), p.get("ef_el"), {"grid": "Grid factor (Annex II of 2025/2621)", "own": "Own generation",
                                                "ppa": "Power purchase agreement"}.get(p.get("el_source"), TODO)]
            for p in inst.get("processes", [])])

    _h(doc, "6. Precursors")
    _table(doc, ["Precursor", "CN code", "Supplier", "Country", "Mass consumed (t)", "Basis", "Evidence"],
           [[p.get("name"), p.get("cn_code"), p.get("supplier"), p.get("country"), p.get("mass_t"), p.get("basis"), p.get("evidence")]
            for p in inst.get("precursors", [])])

    _h(doc, "7. Activity level and attribution")
    doc.add_paragraph("Activity level counts goods leaving the process boundary that are sold or used as a precursor in another "
                      "process; scrap and rejects are excluded. Describe the measuring instruments and stock-change approach.")
    doc.add_paragraph(TODO)

    _h(doc, "8. Data flow, control activities and data gaps")
    doc.add_paragraph("Data flow from meters / invoices to this report, responsibilities, quality checks and record retention. "
                      "Where data are missing, a conservative estimate is used and documented; an unknown biomass fraction is "
                      "taken as zero.")
    doc.add_paragraph(TODO)

    _h(doc, "9. Verification arrangements")
    sv = verification.get("site_visit") or {}
    _table(doc, ["Item", "Value"], [["Verifier", verification.get("verifier_body") or TODO],
                                    ["Accreditation no. / expiry", f"{verification.get('accreditation_no') or TODO} / {verification.get('accreditation_expiry') or TODO}"],
                                    ["Lead auditor", verification.get("lead_auditor") or TODO],
                                    ["Independent reviewer", verification.get("independent_reviewer") or TODO],
                                    ["Site visit", f"{sv.get('type') or TODO}{' - ' + sv['condition'] if sv.get('condition') else ''}"],
                                    ["Report language", verification.get("report_language") or "English"]])
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
