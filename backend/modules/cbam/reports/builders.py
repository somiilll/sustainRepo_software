# ---------------------------------------------------------------- XLSX helpers
def _ws_table(ws, headers: list[str], rows: list[list], start_row: int = 1):
    hf, hfill = Font(name="Arial", bold=True, color="FFFFFF"), PatternFill("solid", fgColor=GREEN)
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=start_row, column=j, value=h)
        c.font, c.fill, c.alignment = hf, hfill, Alignment(wrap_text=True, vertical="center")
        ws.column_dimensions[c.column_letter].width = max(12, min(40, len(h) + 4))
    for i, r in enumerate(rows, start_row + 1):
        for j, v in enumerate(r, 1):
            c = ws.cell(row=i, column=j, value=v)
            c.font = Font(name="Arial")
            if isinstance(v, float):
                c.number_format = "#,##0.000"


def _kv(ws, pairs: list[tuple[str, object]], title: str):
    ws["A1"], ws["A1"].font = title, Font(name="Arial", bold=True, size=14)
    for i, (k, v) in enumerate(pairs, 3):
        ws.cell(row=i, column=1, value=k).font = Font(name="Arial", bold=True)
        c = ws.cell(row=i, column=2, value=v)
        c.font = Font(name="Arial")
        if isinstance(v, float):
            c.number_format = "#,##0.00"
    ws.column_dimensions["A"].width, ws.column_dimensions["B"].width = 48, 60
    ws.cell(row=len(pairs) + 4, column=1, value=DISCLAIMER).font = Font(name="Arial", italic=True, size=8)


def _bytes(wb: Workbook) -> bytes:
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ---------------------------------------------------------------- declaration
def declaration_xlsx(org: dict, year: int, lines: list[dict], s: dict, f) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    _kv(ws, [
        ("Authorised CBAM declarant", org.get("name")), ("Declaration year (imports)", year),
        ("Submission deadline", f"30 September {year + 1}"), ("Net mass imported (t)", s["net_mass"]),
        ("De minimis mass counted (t)", s["deminimis_mass"]), ("Obligated", "Yes" if s["obligated"] else "No"),
        ("Total embedded emissions (tCO2e)", s["embedded"]), ("Free allocation adjustment (tCO2e)", s["faa"]),
        ("Carbon price paid deduction (tCO2e)", s["cp_deduction"]), ("CBAM certificates to surrender", s["certificates"]),
        ("Certificates (whole)", s["certificates_whole"]), ("Estimated cost (EUR)", s["cost"]),
        ("Share of emissions on verified actual data", f"{s['actual_coverage']:.0%}"),
        ("Default values source", load_reference().versions["default_values"]),
        ("Benchmarks source", load_reference().versions["benchmarks"]),
    ], f"CBAM annual declaration {year}")
    ws2 = wb.create_sheet("Goods")
    hdr = ["CN code", "Description", "Origin", "Import date", "Quarter", "Net mass (t)", "Basis", "Installation",
           "Reporting year", "SEE direct", "SEE indirect (counted)", "SEE (tCO2e/t)", "Mark-up", "Route", "SEFA (tCO2e/t)", "CBAM factor", "CSCF",
           "Embedded (tCO2e)", "FAA (tCO2e)", "Carbon price deduction (tCO2e)", "Certificates", "Price (EUR)", "Cost (EUR)", "Error"]
    rows = []
    for l in lines:
        c = l["calc"]
        rows.append([l["cn_code"], l.get("description", ""), l.get("country_of_origin"), l["import_date"], c.get("quarter"),
                     float(l["net_mass"]), l.get("basis"), l.get("installation_name", ""), c.get("reporting_year"),
                     c.get("see_direct"), c.get("see_indirect_counted"), c.get("see"), c.get("markup"), c.get("route"), c.get("sefa"), c.get("cbam_factor"), c.get("cscf"),
                     c.get("embedded"), c.get("faa"), c.get("cp_deduction"), c.get("certificates"), c.get("price"),
                     c.get("cost"), c.get("error") or ""])
    _ws_table(ws2, hdr, rows)
    ws3 = wb.create_sheet("By CN code")
    _ws_table(ws3, ["CN code", "Description", "Sector", "Embedded (tCO2e)", "Certificates"],
              [[r["cn_code"], r["description"], r["sector"], r["embedded"], r["certificates"]] for r in s["by_cn"]])
    ws4 = wb.create_sheet("Factors")
    _ws_table(ws4, ["Year", "CBAM factor", "CSCF", "Default mark-up"],
              [[y, f.factor(y), f.cscf_for(y), f.markup_for(y, "")] for y in range(2026, 2035)])
    return _bytes(wb)


def declaration_json(org: dict, year: int, lines: list[dict], s: dict, f) -> dict:
    """Structured export; field names to be mapped to the definitive-period registry XSD once confirmed."""
    return {
        "schema": "sustainrepo.cbam.declaration/0.1", "declarant": org, "year": year,
        "totals": {k: s[k] for k in ("net_mass", "embedded", "faa", "cp_deduction", "certificates", "certificates_whole")},
        "goods": [{
            "cnCode": l["cn_code"], "countryOfOrigin": l.get("country_of_origin"), "netMass": float(l["net_mass"]),
            "importDate": l["import_date"], "installation": l.get("installation_name"), "determinationType": l.get("basis"),
            "reportingPeriod": l["calc"].get("reporting_year"), "specificEmbeddedEmissions": l["calc"].get("see"),
            "specificEmbeddedFreeAllocation": l["calc"].get("sefa"), "carbonPricePaidPerTonne": l.get("carbon_price_paid") or 0,
            "certificates": l["calc"].get("certificates"), "verificationEvidence": l.get("evidence")}
            for l in lines if not l["calc"]["error"]],
        "referenceVersions": load_reference().versions, "factors": f.to_dict(),
    }


# ---------------------------------------------------------------- PDF helpers
def _pdf(title: str, subtitle: str, blocks: list) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=14 * mm, rightMargin=14 * mm, topMargin=12 * mm, bottomMargin=12 * mm)
    ss = getSampleStyleSheet()
    story = [Paragraph(f"<font color='#{GREEN}'><b>SustainRepo</b></font> · {title}", ss["Title"]),
             Paragraph(subtitle, ss["Normal"]), Spacer(1, 6 * mm)]
    for b in blocks:
        story += [b, Spacer(1, 5 * mm)]
    story.append(Paragraph(f"<font size=7 color='#64748b'>{DISCLAIMER}</font>", ss["Normal"]))
    doc.build(story)
    return buf.getvalue()


def _table(data: list[list], widths=None) -> Table:
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(f"#{GREEN}")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F6F8F7")]),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E2E8F0")), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t


def _n(v, d=2):
    return "-" if v is None else f"{v:,.{d}f}"


def declaration_pdf(org: dict, year: int, lines: list[dict], s: dict) -> bytes:
    kpis = _table([["Net mass (t)", "Embedded (tCO2e)", "Free alloc. adj. (tCO2e)", "Certificates", "Est. cost (EUR)", "Actual-data share"],
                   [_n(s["net_mass"], 1), _n(s["embedded"], 1), _n(s["faa"], 1), f"{s['certificates_whole']:,}", _n(s["cost"], 0), f"{s['actual_coverage']:.0%}"]])
    goods = [["CN", "Origin", "Date", "Mass (t)", "Basis", "SEE", "SEFA", "Certificates", "Cost (EUR)"]]
    for l in lines:
        c = l["calc"]
        goods.append([l["cn_code"], l.get("country_of_origin", ""), l["import_date"], _n(float(l["net_mass"]), 1), l.get("basis"),
                      _n(c.get("see"), 3), _n(c.get("sefa"), 3), _n(c.get("certificates"), 1), _n(c.get("cost"), 0)])
    return _pdf(f"CBAM annual declaration {year}", f"{org.get('name')} · imports 1 Jan – 31 Dec {year} · submit by 30 Sep {year + 1}",
                [kpis, _table(goods)])


# ---------------------------------------------------------------- operator report
def operator_report_xlsx(inst: dict, res: dict) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    _kv(ws, [("Installation", inst["name"]), ("Country", inst.get("country")), ("Reporting period", res["reporting_year"]),
             ("Verification status", inst.get("verification_status")), ("Verifier", inst.get("verifier") or "-"),
             ("Carbon price effectively paid (EUR/t)", inst.get("carbon_price_paid") or 0)],
        "CBAM operator emissions report (summary for declarants)")
    ws2 = wb.create_sheet("Goods")
    hdr = ["Process", "CN code", "Sector", "Activity level (t)", "Attributed direct (tCO2e)", "SEE direct", "SEE indirect",
           "SEE total", "Indirect in scope", "BM* Column A", "SEFA", "Net per t", "Error"]
    _ws_table(ws2, hdr, [[p["name"], p["cn_code"], p.get("sector"), p.get("activity_level_t"), p.get("attr_direct"),
                          p.get("see_direct"), p.get("see_indirect"), p.get("see"), "Yes" if p.get("indirect_in_scope") else "No",
                          p.get("bm_a"), p.get("sefa"), p.get("net_per_t"), p.get("error") or ""] for p in res["processes"]])
    ws3 = wb.create_sheet("Precursors")
    rows = []
    for p in res["processes"]:
        for q in p.get("precursors", []):
            rows.append([p["name"], q.get("name"), q.get("cn_code"), q.get("supplier", ""), q.get("country", ""), q.get("mass_t"),
                         q.get("basis"), q.get("see_direct_used"), q.get("see_indirect_used"), q.get("sefa_used"), q.get("default_source", "")])
    _ws_table(ws3, ["Process", "Precursor", "CN", "Supplier", "Country", "Mass consumed (t)", "Basis", "SEE dir", "SEE indir", "SEFA", "Default source"], rows)
    ws4 = wb.create_sheet("Calculation trace")
    trows = []
    for p in res["processes"]:
        for grp in ("attribution_steps", "see_steps", "sefa_steps"):
            for st in p.get(grp, []):
                trows.append([p["name"], grp.replace("_steps", ""), st["label"], st["formula"], st["value"], st["unit"]])
    _ws_table(ws4, ["Process", "Block", "Step", "Formula", "Value", "Unit"], trows)
    return _bytes(wb)


def operator_report_pdf(inst: dict, res: dict) -> bytes:
    goods = [["Process", "CN", "Activity (t)", "SEE dir", "SEE indir", "SEE total", "SEFA", "Net / t"]]
    for p in res["processes"]:
        goods.append([p["name"], p["cn_code"], _n(p.get("activity_level_t"), 0), _n(p.get("see_direct"), 3), _n(p.get("see_indirect"), 3),
                      _n(p.get("see"), 3), _n(p.get("sefa"), 3), _n(p.get("net_per_t"), 3)])
    return _pdf("CBAM operator emissions report", f"{inst['name']} ({inst.get('country')}) · reporting period {res['reporting_year']} · "
                f"verification: {inst.get('verification_status')}", [_table(goods)])


# ---------------------------------------------------------------- templates
def simple_xlsx(title: str, headers: list[str], rows: list[list], notes: list[str] | None = None) -> bytes:
    """A one-sheet template: header row, example rows, and a Notes sheet."""
    wb = Workbook()
    ws = wb.active
    ws.title = title[:31]
    _ws_table(ws, headers, rows)
    if notes:
        wn = wb.create_sheet("Notes")
        for i, n in enumerate(notes, 1):
            wn.cell(row=i, column=1, value=n).font = Font(name="Arial")
        wn.column_dimensions["A"].width = 110
    return _bytes(wb)


# ---------------------------------------------------------------- operator -> EU importer communication
COMM_HEADERS = ["Shipment / invoice", "Date", "Buyer (EU importer)", "CN code", "Goods", "Quantity (t)", "Production route",
                "SEE direct (tCO2e/t)", "SEE indirect (tCO2e/t)", "Indirect counted", "SEE total (tCO2e/t)",
                "SEFA (tCO2e/t)", "Carbon price paid (EUR/t)", "Embedded total (tCO2e)", "Verification"]


def _comm_rows(shipments: list[dict]) -> list[list]:
    return [[s.get("ref"), s.get("date"), s.get("buyer"), s.get("cn_code"), s.get("process_name"), s.get("quantity_t"),
             s.get("route", ""), s.get("see_direct"), s.get("see_indirect"), "Yes" if s.get("indirect_in_scope") else "No (Annex II)",
             s.get("see"), s.get("sefa"), s.get("carbon_price_eur_per_t") or 0, s.get("embedded"), s.get("verification", "")]
            for s in shipments]


def communication_xlsx(inst: dict, buyer: str, period: str, shipments: list[dict]) -> bytes:
    """Emissions data communication per buyer and period, laid out like the EC communication template:
    installation identification, then embedded emissions per good and per shipment."""
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary_Communication"
    _kv(ws, [("Installation", inst["name"]), ("Country", inst.get("country")), ("Operator / facility ref", inst.get("facility_id")),
             ("Reporting period", period), ("Buyer (EU importer)", buyer or "All buyers"),
             ("Verification status", inst.get("verification_status")), ("Verifier", inst.get("verifier") or "-"),
             ("Shipments", len(shipments)), ("Total quantity (t)", float(sum(s.get("quantity_t") or 0 for s in shipments))),
             ("Total embedded emissions (tCO2e)", float(sum(s.get("embedded") or 0 for s in shipments)))],
        "Emissions data communication to EU importer")
    _ws_table(wb.create_sheet("Shipments"), COMM_HEADERS, _comm_rows(shipments))
    return _bytes(wb)


def communication_pdf(inst: dict, buyer: str, period: str, shipments: list[dict]) -> bytes:
    data = [["Shipment", "Date", "Buyer", "CN", "Qty (t)", "SEE dir", "SEE ind", "SEE", "SEFA", "Embedded"]]
    for s in shipments:
        data.append([s.get("ref"), s.get("date"), s.get("buyer"), s.get("cn_code"), _n(s.get("quantity_t"), 1),
                     _n(s.get("see_direct"), 3), _n(s.get("see_indirect"), 3), _n(s.get("see"), 3), _n(s.get("sefa"), 3),
                     _n(s.get("embedded"), 1)])
    return _pdf("Emissions data communication", f"{inst['name']} ({inst.get('country')}) · {period} · buyer: {buyer or 'all'} · "
                f"verification: {inst.get('verification_status')}", [_table(data)])
